                            {
                                VendaPOSVisao.cmbCliente.setModel( new DefaultComboBoxModel( clienteDao.buscaTodos() ) );
                                VendaPOSVisao.cmbCliente.setSelectedItem( clienteGlobal.getNome() );
                                dispose();
                            }
